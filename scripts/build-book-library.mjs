#!/usr/bin/env node
// Convert the bundled Gutenberg source into chapters; never fetch at runtime.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const source = readFileSync(new URL('../books/wizard-of-oz-source.txt', import.meta.url), 'utf8')
  .replace(/\r\n?/g, '\n');
const start = source.indexOf('*** START OF THE PROJECT GUTENBERG EBOOK');
const end = source.indexOf('*** END OF THE PROJECT GUTENBERG EBOOK');
if (start < 0 || end <= start) throw new Error('Missing Gutenberg source boundaries');
const story = source.slice(source.indexOf('\n', start), end);
const headings = [...story.matchAll(/^Chapter ([IVXLCDM]+)\n([^\n]+)\n/gm)];
if (headings.length !== 24) throw new Error(`Expected 24 chapters; got ${headings.length}`);

function paragraphs(text) {
  return text.replace(/^\[Illustration[^\n]*\]\s*$/gm, '')
    .trim().split(/\n\s*\n/)
    .map(p => p.replace(/\s*\n\s*/g, ' ').trim()).filter(Boolean).join('\n\n');
}

const chapters = headings.map((match, index) => ({
  number: index + 1,
  title: match[2].trim(),
  text: paragraphs(story.slice(match.index + match[0].length, headings[index + 1]?.index ?? story.length)),
}));
if (chapters.some(c => c.text.length < 100 || c.text.length > 200000)) {
  throw new Error('Unexpected chapter length');
}
const intro = story.slice(0, headings[0].index).match(/\nIntroduction\n+([\s\S]*?)\nThe Wonderful Wizard of Oz\s*$/);
if (!intro) throw new Error('Missing author introduction');
const books = [{
  id: 'wizard-of-oz',
  title: 'The Wonderful Wizard of Oz',
  titleCN: '绿野仙踪',
  author: 'L. Frank Baum',
  published: 1900,
  sourceUrl: 'https://www.gutenberg.org/ebooks/55',
  sourceFile: 'books/wizard-of-oz-source.txt',
  recommendation: 'Start here: a clear adventure with dialogue and 24 chapters. Some words are old-fashioned. Try Chapter 1 for 10–15 minutes and see whether you can follow the story.',
  introduction: paragraphs(intro[1]),
  chapters,
}];
const out = fileURLToPath(new URL('../books/library.js', import.meta.url));
writeFileSync(out, `// Generated by scripts/build-book-library.mjs. Source and license: wizard-of-oz-source.txt.\n(function (root) {\n  'use strict';\n  const books = ${JSON.stringify(books, null, 2)};\n  if (typeof module !== 'undefined' && module.exports) module.exports = books;\n  else root.BookLibrary = books;\n})(typeof window !== 'undefined' ? window : globalThis);\n`);
console.log(`Bundled ${chapters.length} original chapters in ${out}`);
